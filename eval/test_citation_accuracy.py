
"""
Part F - Test 3
Citation accuracy through the real answer pipeline.

Measures whether citations generated by the real LLM are supported
by the retrieved BNSS context.

Pipeline:

Golden set
    -> HybridRetriever
    -> real LLM
    -> citation_guard
    -> citation accuracy

Metrics:
    - total citations generated
    - valid citations
    - invalid/hallucinated citations
    - citation accuracy
    - answers with citations
    - answers with hallucinated citations
"""

import json
import os
import sys
import time
import statistics

# ---------------------------------------------------------
# Project root
# ---------------------------------------------------------

PROJECT_ROOT = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..")
)

sys.path.insert(0, PROJECT_ROOT)

# ---------------------------------------------------------
# Imports
# ---------------------------------------------------------

from sentence_transformers import SentenceTransformer, CrossEncoder

from backend.app.retrieval.qdrant_store import VectorStore
from backend.app.retrieval.bm25_index import BM25Index
from backend.app.retrieval.hybrid_search import HybridRetriever

from backend.app.llm.providers import get_llm_provider
from backend.app.llm.answer import answer_question

from backend.app.llm.citation_guard import (
    extract_cited_sections,
)


# ---------------------------------------------------------
# Configuration
# ---------------------------------------------------------

GOLDEN_FILE = "eval/golden_set.jsonl"

CHUNKS_FILE = "data/processed/bnss_chunks.jsonl"

QDRANT_URL = "http://localhost:6333"

EMBED_MODEL = "BAAI/bge-base-en-v1.5"

VECTOR_SIZE = 768


# ---------------------------------------------------------
# Load golden set
# ---------------------------------------------------------

def load_golden_set(path):

    rows = []

    with open(path, "r", encoding="utf-8") as f:

        for line in f:

            line = line.strip()

            if line:
                rows.append(json.loads(line))

    return rows


# ---------------------------------------------------------
# Setup
# ---------------------------------------------------------

print("=" * 70)
print("PART F - TEST 3: CITATION ACCURACY")
print("=" * 70)


print("\nLoading BNSS chunks...")

with open(CHUNKS_FILE, "r", encoding="utf-8") as f:

    chunks = [
        json.loads(line)
        for line in f
        if line.strip()
    ]

print(f"Loaded {len(chunks)} BNSS chunks")


print(f"\nLoading embedding model: {EMBED_MODEL}")

model = SentenceTransformer(EMBED_MODEL)

print("Embedding model loaded.")


def embed_query(query: str) -> list[float]:

    return model.encode(
        "query: " + query,
        normalize_embeddings=True,
    ).tolist()


print("\nLoading BM25 index...")

bm25 = BM25Index(chunks)

print("BM25 index loaded.")


print(f"\nConnecting to Qdrant at {QDRANT_URL}...")

store = VectorStore(
    url=QDRANT_URL,
    vector_size=VECTOR_SIZE,
)

print("Qdrant connection ready.")


print("\nLoading cross-encoder reranker...")

cross_encoder = CrossEncoder(
    "cross-encoder/ms-marco-MiniLM-L-6-v2"
)

print("Cross-encoder loaded.")


def rerank(query, candidates):

    if not candidates:
        return []

    pairs = [
        (
            query,
            c["payload"].get("text", "")
        )
        for c in candidates
    ]

    scores = cross_encoder.predict(pairs)

    for candidate, score in zip(candidates, scores):

        candidate["rerank_score"] = float(score)

    return sorted(
        candidates,
        key=lambda x: x["rerank_score"],
        reverse=True,
    )


retriever = HybridRetriever(
    store,
    bm25,
    embed_query,
    reranker=rerank,
)


print("\nLoading LLM provider...")

llm = get_llm_provider()

print("LLM provider ready.")


# ---------------------------------------------------------
# Questions
# ---------------------------------------------------------

rows = load_golden_set(GOLDEN_FILE)

# Only evaluate questions that should actually produce
# legal answers. Must-refuse questions are excluded because
# a refusal legitimately contains no citation.

questions = [
    row
    for row in rows
    if row.get("type") != "must_refuse"
]

print(
    f"\nGolden-set questions: {len(rows)}"
)

print(
    f"Citation evaluation questions: {len(questions)}"
)


# ---------------------------------------------------------
# Metrics
# ---------------------------------------------------------

total_citations = 0
valid_citations = 0
invalid_citations = 0

answers_with_citations = 0
answers_without_citations = 0
answers_with_hallucination = 0

answer_latencies = []


# ---------------------------------------------------------
# Run test
# ---------------------------------------------------------

print("\n" + "=" * 70)
print("RUNNING CITATION ACCURACY TEST")
print("=" * 70)


for index, row in enumerate(
    questions,
    start=1,
):

    question = row["q"]

    print("\n" + "-" * 70)
    print(
        f"Question {index}/{len(questions)}"
    )
    print(f"Q: {question}")

    # -----------------------------------------------------
    # Retrieval
    # -----------------------------------------------------

    retrieval_start = time.perf_counter()

    retrieval_result = retriever.search(
        question,
        top_k=10,
    )

    retrieval_time = (
        time.perf_counter()
        - retrieval_start
    )

    # -----------------------------------------------------
    # Answer generation + citation validation
    # -----------------------------------------------------

    answer_start = time.perf_counter()

    result = answer_question(
        question,
        retrieval_result,
        llm,
    )

    answer_time = (
        time.perf_counter()
        - answer_start
    )

    answer_latencies.append(
        answer_time
    )

    # -----------------------------------------------------
    # Analyze ORIGINAL LLM output
    # -----------------------------------------------------

    raw_answer = result.get(
        "_debug_raw_answer"
    )

    if raw_answer is None:
        raw_answer = result.get(
            "answer",
            ""
        )

    citations = extract_cited_sections(
        raw_answer
    )

    num_citations = len(citations)

    total_citations += num_citations

    # -----------------------------------------------------
    # Valid / invalid citations
    #
    # answer_question() already ran the citation guard.
    # invalid_citations_stripped contains the citations
    # that failed validation.
    # -----------------------------------------------------

    invalid = result.get(
        "invalid_citations_stripped",
        []
    )

    num_invalid = len(invalid)

    num_valid = max(
        0,
        num_citations - num_invalid
    )

    valid_citations += num_valid
    invalid_citations += num_invalid

    if num_citations > 0:
        answers_with_citations += 1
    else:
        answers_without_citations += 1

    if num_invalid > 0:
        answers_with_hallucination += 1

    # -----------------------------------------------------
    # Print question result
    # -----------------------------------------------------

    print(
        f"Citations generated: "
        f"{num_citations}"
    )

    print(
        f"Valid citations:     "
        f"{num_valid}"
    )

    print(
        f"Invalid citations:   "
        f"{num_invalid}"
    )

    print(
        f"Refused:             "
        f"{result.get('refused')}"
    )

    print(
        f"Retrieval latency:   "
        f"{retrieval_time * 1000:.2f} ms"
    )

    print(
        f"Generation latency:  "
        f"{answer_time * 1000:.2f} ms"
    )

    if invalid:

        print(
            "Hallucinated citations:"
        )

        for citation in invalid:
            print(
                f"  - BNSS s."
                f"{citation[0]}"
                f"{'(' + citation[1] + ')' if citation[1] else ''}"
            )

    print(
        f"Final answer:\n"
        f"{result.get('answer', '')[:500]}"
    )


# ---------------------------------------------------------
# Aggregate metrics
# ---------------------------------------------------------

citation_accuracy = (
    valid_citations / total_citations
    if total_citations
    else 0.0
)

hallucination_rate = (
    invalid_citations / total_citations
    if total_citations
    else 0.0
)

citation_coverage = (
    answers_with_citations / len(questions)
    if questions
    else 0.0
)

if answer_latencies:

    p50_generation = statistics.median(
        answer_latencies
    )

    sorted_latencies = sorted(
        answer_latencies
    )

    p95_index = min(
        int(len(sorted_latencies) * 0.95),
        len(sorted_latencies) - 1,
    )

    p95_generation = (
        sorted_latencies[p95_index]
    )

else:

    p50_generation = 0.0
    p95_generation = 0.0


# ---------------------------------------------------------
# Final output
# ---------------------------------------------------------

print("\n" + "=" * 70)
print("TEST 3 RESULTS")
print("=" * 70)

print(
    f"Evaluation questions:       "
    f"{len(questions)}"
)

print(
    f"Total citations generated:  "
    f"{total_citations}"
)

print(
    f"Valid citations:             "
    f"{valid_citations}"
)

print(
    f"Invalid citations:           "
    f"{invalid_citations}"
)

print(
    f"Citation accuracy:           "
    f"{citation_accuracy:.4f}"
)

print(
    f"Citation accuracy:           "
    f"{citation_accuracy * 100:.2f}%"
)

print(
    f"Citation coverage:           "
    f"{citation_coverage * 100:.2f}%"
)

print(
    f"Hallucination rate:          "
    f"{hallucination_rate * 100:.2f}%"
)

print(
    f"Answers with citations:      "
    f"{answers_with_citations}"
)

print(
    f"Answers without citations:   "
    f"{answers_without_citations}"
)

print(
    f"Answers with hallucination:  "
    f"{answers_with_hallucination}"
)

print()

print(
    f"Generation p50:              "
    f"{p50_generation * 1000:.2f} ms"
)

print(
    f"Generation p95:              "
    f"{p95_generation * 1000:.2f} ms"
)

print("=" * 70)


# ---------------------------------------------------------
# Save results
# ---------------------------------------------------------

output = {

    "test": "citation_accuracy",

    "evaluation_questions": len(questions),

    "total_citations_generated":
        total_citations,

    "valid_citations":
        valid_citations,

    "invalid_citations":
        invalid_citations,

    "citation_accuracy":
        citation_accuracy,

    "citation_coverage":
        citation_coverage,

    "hallucination_rate":
        hallucination_rate,

    "answers_with_citations":
        answers_with_citations,

    "answers_without_citations":
        answers_without_citations,

    "answers_with_hallucination":
        answers_with_hallucination,

    "generation_p50_ms":
        p50_generation * 1000,

    "generation_p95_ms":
        p95_generation * 1000,
}


output_file = "eval/citation_results.json"

with open(
    output_file,
    "w",
    encoding="utf-8",
) as f:

    json.dump(
        output,
        f,
        indent=2,
    )


print(
    f"\nResults written to: "
    f"{output_file}"
)

